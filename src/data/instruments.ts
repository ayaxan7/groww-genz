type StockSeed = Omit<Instrument, "type" | "minAmount" | "sipEligible" | "financials"> & {
  mcap: string;
  pe: number;
  revenue: string;
  profit: string;
};

const stock = (s: StockSeed): Instrument => {
  const { mcap, pe, revenue, profit, ...rest } = s;
  return {
    ...rest,
    type: "stock",
    minAmount: Math.ceil(rest.price),
    sipEligible: true,
    financials: [
      { label: "Market cap", value: mcap },
      { label: "P/E ratio", value: pe.toFixed(1) },
      { label: "Revenue (FY)", value: revenue },
      { label: "Net profit (FY)", value: profit },
    ],
  };
};

type FundSeed = Omit<Instrument, "minAmount" | "sipEligible" | "financials" | "type"> & {
  aum: string;
  expense: string;
  holdingsCount: number;
};

const fund = (type: Extract<InstrumentType, "mf" | "etf">, s: FundSeed): Instrument => {
  const { aum, expense, holdingsCount, ...rest } = s;
  return {
    ...rest,
    type,
    minAmount: type === "mf" ? 100 : Math.ceil(rest.price),
    sipEligible: true,
    financials: [
      { label: type === "mf" ? "NAV" : "Price per unit", value: `₹${rest.price.toFixed(2)}` },
      { label: "Fund size (AUM)", value: aum },
      { label: "Expense ratio", value: expense },
      { label: "Holdings", value: `${holdingsCount} companies` },
    ],
  };
};

